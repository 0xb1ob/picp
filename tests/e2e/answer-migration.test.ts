/**
 * M2 PR2 repair: the legacy answers journal migration through its real entry points (cp_parent answer on a cp-bridge
 * pi, the parent pi's startup tick), on the journal the pre-M2 writers produce, under races and mid-migration changes.
 */
import assert from "node:assert/strict";
import { appendFileSync, copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { type TestContext, test } from "node:test";
import { fileURLToPath } from "node:url";
import { EscalationStore } from "../../src/escalation.ts";
import { answerJournals } from "../../src/migrate-answer-reports.ts";
import { readResponseReport, RESPONSE_INLINE_MAX } from "../../src/response-reports.ts";
import { resolveStateDir } from "../../src/viewer/sessions.ts";
import { COMMAND_POST_EXTENSION, CP_BRIDGE_EXTENSION, createAgentDir, createScratchHome, MockProvider, type PiChild, startPiChild } from "../harness/index.ts";

// Generated by the pre-M2 writers at ac0713a457fc (OperatorAnswers.post/postScheduleResult, POST /api/answers/ack);
// its key sets and counts mirror the live census (208 bridge posts, 6 schedule posts, 83 acks), with no real content.
const FIXTURE = fileURLToPath(new URL("../fixtures/legacy-answers-ac0713a4.jsonl", import.meta.url));
const VIEWER_ENV = { CP_VIEWER_HOST: "127.0.0.2", CP_VIEWER_PORT: "9911" };
type Home = ReturnType<typeof createScratchHome>;
type Line = Record<string, any>;

/** The home seeded with the fixture; `ms` rewrites the first line's time in Date.toISOString's millisecond form. */
function seed(t: TestContext, ms = false): { home: Home; live: string; archive: string; bytes: string; lines: Line[] } {
	const home = createScratchHome();
	t.after(() => home.cleanup());
	const { live, archive } = answerJournals(home.path);
	mkdirSync(dirname(live), { recursive: true });
	copyFileSync(FIXTURE, live);
	if (ms) {
		const [first, ...rest] = readFileSync(live, "utf8").split("\n");
		const line = JSON.parse(first!);
		writeFileSync(live, [JSON.stringify({ ...line, at: new Date(line.at).toISOString() }), ...rest].join("\n"));
	}
	const bytes = readFileSync(live, "utf8");
	return { home, live, archive, bytes, lines: bytes.trim().split("\n").map((row) => JSON.parse(row)) };
}

const boards = (home: string) => {
	const dir = join(resolveStateDir(home), "boards");
	return existsSync(dir) ? readdirSync(dir).filter((name) => !name.startsWith(".")) : [];
};

/** A cp-bridge pi whose one tool call posts `answer` as cp_parent answer; returns its prompt and its tool result. */
async function bridge(t: TestContext, home: Home, answer: string) {
	const provider = await MockProvider.start();
	const model = provider.addScript(`bridge-${Math.random().toString(16).slice(2)}`, [
		{ kind: "tool_calls", calls: [{ id: "post", name: "cp_parent", args: { action: "answer", project: "demo", question: "Does it work?", answer } }] },
		{ kind: "text", text: "Done." },
	]);
	const agent = createAgentDir({ provider });
	const pi = startPiChild({ cwd: home.path, model, env: { ...agent.env, PI_HOME: home.path, CP_HOME: home.path, CP_MODE: "multi", ...VIEWER_ENV }, extensions: [CP_BRIDGE_EXTENSION] });
	t.after(async () => { await pi.close(); agent.cleanup(); await provider.stop(); });
	return {
		post: async () => {
			await pi.prompt("Post it.");
			await pi.waitFor((r) => r.type === "agent_settled", 60_000);
			const end = pi.records().find((r) => r.type === "tool_execution_end") as unknown as { isError?: boolean; result?: { content?: { text?: string }[] } };
			return { isError: end.isError === true, text: end.result?.content?.[0]?.text ?? "" };
		},
	};
}

async function parent(t: TestContext, home: Home): Promise<PiChild> {
	const provider = await MockProvider.start();
	const model = provider.addScript(`parent-${Math.random().toString(16).slice(2)}`, [{ kind: "text", text: "checked" }]);
	const agent = createAgentDir({ provider });
	const pi = startPiChild({ cwd: home.path, model, env: { ...agent.env, CP_HOME: home.path, ...VIEWER_ENV }, extensions: [COMMAND_POST_EXTENSION] });
	t.after(async () => { await pi.close(); agent.cleanup(); await provider.stop(); });
	return pi;
}

const long = (tag: string) => `${tag}\n\n${"y".repeat(RESPONSE_INLINE_MAX)}`;

// The race: a parent's startup tick and two cp_parent answer calls run the gate on one home at once. Every loser
// sees the winner's publish or rename as done: no error, no escalation, each legacy answer one report, archive intact.
test("M2-migration-race: concurrent gates on the real-writer journal migrate once, with no loser failing", { timeout: 240_000 }, async (t) => {
	const s = seed(t, true);
	const [a, b] = await Promise.all([bridge(t, s.home, long("first")), bridge(t, s.home, long("second"))]);
	const [, first, second] = await Promise.all([parent(t, s.home), a.post(), b.post()]);
	for (const sent of [first, second]) assert.equal(sent.isError, false, sent.text);
	assert.deepEqual([existsSync(s.live), readFileSync(s.archive, "utf8")], [false, s.bytes], "renamed once, bytes kept");
	const posted = new Map(s.lines.filter((line) => line.type === "posted").map((line) => [line.id, line]));
	assert.deepEqual([posted.size, s.lines.length], [214, 297]);
	for (const [id, line] of posted) {
		assert.deepEqual(readResponseReport(s.home.path, `legacy:${id}`)?.payload, {
			project: line.project, question: line.question, answer: line.answer, evidence: line.evidence_paths, job: line.job_id, source: `legacy:${id}`,
			time: line.at.replace(/\.\d{3}Z$/, "Z"),
		}, id);
	}
	assert.match(s.lines[0]!.at, /\.\d{3}Z$/, "the millisecond line was migrated with whole-second time");
	assert.equal(boards(s.home.path).length, 216, "214 legacy reports plus the two new answers");
	await new Promise((resolve) => setTimeout(resolve, 2000));
	assert.deepEqual(new EscalationStore({ home: s.home.path }).list({ kind: "service_health" }), [], "a race is never an escalation");
});

// Changed snapshot: a straggling pre-M2 writer appends while the bridge migrates; the recheck before the rename sees it.
test("M2-migration-changed-snapshot: a journal that changes mid-migration fails closed, named, nothing renamed", { timeout: 120_000 }, async (t) => {
	const s = seed(t);
	const a = await bridge(t, s.home, long("changed"));
	const ack = `${JSON.stringify(s.lines.find((line) => line.type === "acked"))}\n`;
	let appends = 0;
	const writer = setInterval(() => { if (boards(s.home.path).length) { appendFileSync(s.live, ack); appends++; } }, 2);
	const sent = await a.post().finally(() => clearInterval(writer));
	assert.ok(appends > 0, "the writer appended during the migration");
	assert.equal(sent.isError, true);
	assert.match(sent.text, /answer migration failed, \S+answers\.jsonl left unchanged: recheck: the journal changed while migrating/);
	assert.deepEqual([readFileSync(s.live, "utf8"), existsSync(s.archive)], [s.bytes + ack.repeat(appends), false], "nothing renamed or deleted");
});

// Archive collision: answers.jsonl.migrated appears after the gate's first look; the gate refuses to rename over it.
test("M2-migration-archive-collision: an archive that appears mid-migration is the named conflict, both files kept", { timeout: 120_000 }, async (t) => {
	const s = seed(t);
	const a = await bridge(t, s.home, long("collision"));
	const stray = "stray archive\n";
	const writer = setInterval(() => { if (boards(s.home.path).length && !existsSync(s.archive)) writeFileSync(s.archive, stray); }, 2);
	const sent = await a.post().finally(() => clearInterval(writer));
	assert.equal(sent.isError, true);
	assert.match(sent.text, /answer migration conflict: live and migrated journals both exist/);
	assert.deepEqual([readFileSync(s.live, "utf8"), readFileSync(s.archive, "utf8")], [s.bytes, stray], "neither file overwritten");
});
