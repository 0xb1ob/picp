/**
 * cp-daemon P2: the legacy unit texts (src/service/units.ts). Retained (P14b): cp-install renders `renderUnits` only as a
 * port and word check and discards it (install.ts), so no entry point writes these units; LEGACY_UNITS is a constant parity.
 */
import assert from "node:assert/strict";
import { test } from "node:test";
import { LEGACY_UNITS } from "../src/service/daemon-backend.ts";
import { unitNode } from "../src/service/status.ts";
import { HEALTH_TIMER, HEALTH_UNIT, OPERATOR_RESUME_UNIT, OPERATOR_UNIT, PARENT_UNIT, renderUnits, UPDATE_TIMER, UPDATE_UNIT, VIEW_UNIT } from "../src/service/units.ts";

const input = { node: "/opt/node/bin/node", app: "/home/u/.pi-command-post/app", home: "/home/u/.pi-command-post", path: "/opt/node/bin:/usr/bin", port: 8766 };

test("cp-parent.service: attach-first supervisor, crash-loop stop, no-model stop, KillMode=process, CP_HOME", () => {
	const text = renderUnits({ ...input, parentModel: "anthropic/claude-opus-4-6" })[PARENT_UNIT]!;
	for (const line of [
		'ExecStart="/opt/node/bin/node" "/home/u/.pi-command-post/app/src/service/supervise.ts"',
		"WorkingDirectory=/home/u/.pi-command-post",
		'Environment="CP_HOME=/home/u/.pi-command-post"',
		'Environment="CP_MODE=multi"',
		'Environment="PATH=/opt/node/bin:/usr/bin"',
		'Environment="CP_VIEWER_PORT=8766"',
		'Environment="CP_PARENT_MODEL=anthropic/claude-opus-4-6"',
		"Restart=on-failure", "RestartSec=5", "RestartSteps=5", "RestartMaxDelaySec=300",
		"RestartPreventExitStatus=78", "KillMode=process", "TimeoutStopSec=10",
		"StartLimitIntervalSec=1800", "StartLimitBurst=6", "WantedBy=default.target",
	]) assert.ok(text.split("\n").includes(line), `missing ${line}\n${text}`);
	assert.equal(unitNode(text), "/opt/node/bin/node");
	assert.doesNotMatch(renderUnits(input)[PARENT_UNIT]!, /CP_PARENT_MODEL/, "no model named → none recorded");
});

test("daemon-backend's LEGACY_UNITS are units.ts's legacy unit names (the backend cannot import units.ts)", () => {
	assert.deepEqual([...LEGACY_UNITS], [PARENT_UNIT, VIEW_UNIT, HEALTH_UNIT, HEALTH_TIMER, UPDATE_UNIT, UPDATE_TIMER]);
});

test("cp-view.service: the viewer on the tailnet, always restarted", () => {
	const text = renderUnits(input)[VIEW_UNIT]!;
	assert.ok(text.includes('ExecStart="/opt/node/bin/node" "/home/u/.pi-command-post/app/src/viewer/cli.ts" "--home" "/home/u/.pi-command-post" "--require-tailnet" "--port" "8766"'), text);
	for (const line of ["Restart=always", "RestartSec=10", "StartLimitIntervalSec=0"]) assert.ok(text.split("\n").includes(line), line);
});

test("cp-health.service + cp-health.timer: a oneshot watchdog every 5 minutes, from 3 minutes after boot", () => {
	const units = renderUnits(input);
	const service = units[HEALTH_UNIT]!.split("\n");
	for (const line of ["Type=oneshot", "TimeoutStartSec=120", 'ExecStart="/opt/node/bin/node" "/home/u/.pi-command-post/app/src/service/health.ts"', 'Environment="CP_HOME=/home/u/.pi-command-post"', 'Environment="CP_VIEWER_PORT=8766"']) assert.ok(service.includes(line), line);
	assert.ok(!service.includes("[Install]"), "the service runs from its timer, never enabled itself");
	const timer = units[HEALTH_TIMER]!.split("\n");
	for (const line of ["OnBootSec=3min", "OnUnitActiveSec=5min", `Unit=${HEALTH_UNIT}`, "WantedBy=timers.target"]) assert.ok(timer.includes(line), line);
});

test("cp-update.service + cp-update.timer: a oneshot updater in its own unit every 5 minutes, from 10 minutes after boot", () => {
	const units = renderUnits(input);
	const service = units[UPDATE_UNIT]!.split("\n");
	for (const line of ["Type=oneshot", "TimeoutStartSec=45min", 'ExecStart="/opt/node/bin/node" "/home/u/.pi-command-post/app/src/service/update.ts"', 'Environment="CP_HOME=/home/u/.pi-command-post"', 'Environment="CP_MODE=multi"', 'Environment="CP_VIEWER_PORT=8766"']) assert.ok(service.includes(line), line);
	assert.ok(!service.includes("[Install]"), "the service runs from its timer, never enabled itself");
	const timer = units[UPDATE_TIMER]!.split("\n");
	for (const line of ["OnBootSec=10min", "OnUnitActiveSec=5min", `Unit=${UPDATE_UNIT}`, "WantedBy=timers.target"]) assert.ok(timer.includes(line), line);
});

test("cp-operator.service: the pinned text — forking tmux with the wrapper, killed by session name; rendered only with tmux", () => {
	assert.equal(renderUnits(input)[OPERATOR_UNIT], undefined, "no tmux, no unit");
	assert.equal(renderUnits({ ...input, tmux: "/usr/bin/tmux", wrapper: "/home/u/.local/bin/cp-operator" })[OPERATOR_UNIT], [
		"# Generated by cp-install (pi-command-post); edits are refused on reinstall without --force.",
		"[Unit]",
		"Description=pi-command-post operator session in tmux (never at boot; the dashboard's Start session)",
		"",
		"[Service]",
		"Type=forking",
		'ExecStart="/usr/bin/tmux" "new-session" "-d" "-s" "cp-operator" "/home/u/.local/bin/cp-operator"',
		'ExecStop="/usr/bin/tmux" "kill-session" "-t" "cp-operator"',
		"WorkingDirectory=/home/u/.pi-command-post",
		'Environment="CP_HOME=/home/u/.pi-command-post"',
		'Environment="CP_MODE=multi"',
		'Environment="PATH=/opt/node/bin:/usr/bin"',
		"",
		"[Install]",
		"WantedBy=default.target",
		"",
	].join("\n"));
});

test("cp-operator-resume.service: the same unit with the fixed `-c` on the wrapper; rendered only with tmux", () => {
	assert.equal(renderUnits(input)[OPERATOR_RESUME_UNIT], undefined, "no tmux, no unit");
	const units = renderUnits({ ...input, tmux: "/usr/bin/tmux", wrapper: "/home/u/.local/bin/cp-operator" });
	const resume = units[OPERATOR_RESUME_UNIT]!.split("\n");
	assert.ok(resume.includes('ExecStart="/usr/bin/tmux" "new-session" "-d" "-s" "cp-operator" "/home/u/.local/bin/cp-operator" "-c"'), resume.join("\n"));
	assert.deepEqual(resume.filter((line) => !line.startsWith("ExecStart=") && !line.startsWith("Description=")), units[OPERATOR_UNIT]!.split("\n").filter((line) => !line.startsWith("ExecStart=") && !line.startsWith("Description=")), "otherwise the same unit");
});
