/**
 * cp-daemon's backend port (cp-txbb): how this machine runs cp-daemon, and the only module that names
 * `systemctl`, `loginctl` or `journalctl` (tests/structure.test.ts ratchets it).
 *
 *   systemd    a thin `cp-daemon.service` runs `cp-daemon run` in the foreground (`renderDaemonUnit`);
 *              linger keeps it up without a login session
 *   detached   no user manager (a Coder VM): `cp-daemon start` setsid-spawns `run`; after a reboot the
 *              printed reboot command (or the opt-in `--crontab` @reboot line) starts it again
 *
 * `migrateLegacy` (M1, docs/service.md §Migration) moves a home off the six legacy units
 * (`cp-parent`/`cp-view` + the health and update timers) without touching the parent host or its
 * workers; `activate`/`deactivate` are cp-install's start and uninstall; `daemonFindings` and
 * `viewerExpected` feed /doctor (`status.ts`). Imports only `node:*` and `./daemon-*.ts`: daemon.ts loads it
 * into the outer process (`OUTER_SOURCES`).
 */
import { existsSync, readFileSync } from "node:fs";
import { userInfo } from "node:os";
import { join } from "node:path";
import {
	type Backend,
	type DaemonConfig,
	type DaemonPaths,
	daemonPaths,
	type DaemonState,
	type LockRecord,
	OUTER_ARGV,
	outerHash,
	pidAlive,
	psArgs,
	readDaemonConfig,
	readJson,
	rebootCommand,
	type RuntimeRecord,
	sameProcess,
} from "./daemon-files.ts";

export const DAEMON_UNIT = "cp-daemon.service";
/** What cp-install wrote before cp-daemon (units.ts renders them; tests/daemon-backend.test.ts pins the names). */
export const LEGACY_UNITS = ["cp-parent.service", "cp-view.service", "cp-health.service", "cp-health.timer", "cp-update.service", "cp-update.timer"] as const;
const [PARENT, VIEW, , HEALTH_TIMER, UPDATE, UPDATE_TIMER] = LEGACY_UNITS;
/** The legacy units install enabled; the oneshots ran from their timers. */
const LEGACY_ENABLED = [PARENT, VIEW, HEALTH_TIMER, UPDATE_TIMER];
const GENERATED = "Generated by cp-install";
export const READY_WAIT_MS = 60_000;

export interface RunResult { status: number; stdout: string; stderr: string }
export type Run = (command: string, args: readonly string[]) => RunResult;
type Step = (status: "ok" | "changed" | "skip" | "fail", name: string, detail: string) => void;

export function detectBackend(run: Run): { backend: Backend; detail: string } {
	const state = run("systemctl", ["--user", "is-system-running"]).stdout.trim();
	if (state === "running" || state === "degraded") return { backend: "systemd", detail: `systemctl --user is ${state}: cp-daemon runs as ${DAEMON_UNIT}` };
	return { backend: "detached", detail: `no systemd --user (${state || "unavailable"}): cp-daemon runs detached; after a reboot run the reboot command it prints` };
}

/** The CLI's start/stop/restart on the systemd backend: the unit is the process manager. */
export function systemdVerb(verb: "start" | "stop" | "restart", run: Run): { code: number; text: string } {
	const result = run("systemctl", ["--user", verb, DAEMON_UNIT]);
	return result.status === 0
		? { code: 0, text: `cp-daemon: systemctl --user ${verb} ${DAEMON_UNIT}: ok${verb === "stop" ? " (the parent host and workers keep running)" : ""}` }
		: { code: 1, text: `cp-daemon ${verb}: systemctl --user ${verb} ${DAEMON_UNIT} failed: ${result.stderr.trim() || `exit ${result.status}`}; journalctl --user -u ${DAEMON_UNIT} -n 20` };
}

/** How to start a stopped daemon, also after a reboot. */
export function startCommand(config: Pick<DaemonConfig, "backend" | "node" | "app" | "home">): string {
	return config.backend === "systemd" ? `systemctl --user start ${DAEMON_UNIT}` : rebootCommand(config);
}

