export interface BackendFinding { check: string; severity: "ok" | "warn" | "error"; what: string; detail?: string; fix?: string }
export type Probe = { alive(pid: number): boolean; argsOf(pid: number): string | undefined };
type FindRun = (command: string, args: string[], cwd: string) => { status: number | null; stdout: string };

const fileText = (path: string): string | undefined => (existsSync(path) ? readFileSync(path, "utf8") : undefined);

/**
 * `service.daemon` (when `data/daemon.json` exists) and `service.legacy_units` (when a legacy unit file is
 * present: warn, never error — verify after an update rejects only errors). Nothing installed → nothing.
 */
export function daemonFindings(run: FindRun, home: string, unitDir: string, probe: Probe = { alive: pidAlive, argsOf: psArgs }): BackendFinding[] {
	const findings: BackendFinding[] = [];
	const paths = daemonPaths(home);
	let config: DaemonConfig | undefined;
	try {
		config = readDaemonConfig(paths.config);
	} catch (error) {
		findings.push({ check: "service.daemon", severity: "warn", what: (error as Error).message, fix: "rerun cp-install --force (it rewrites data/daemon.json)" });
	}
	if (config) findings.push(daemonFinding(run, home, paths, config, probe));
	const legacy = LEGACY_UNITS.filter((name) => existsSync(join(unitDir, name)));
	if (legacy.length) {
		findings.push({
			check: "service.legacy_units",
			severity: "warn",
			what: `${legacy.length} legacy unit(s) in ${unitDir}`,
			detail: legacy.join(", "),
			fix: "this home still runs the legacy cp-* units and auto-update records migration_required: rerun cp-install to move it to cp-daemon (docs/service.md §Migration)",
		});
	}
	return findings;
}

function daemonFinding(run: FindRun, home: string, paths: DaemonPaths, config: DaemonConfig, probe: Probe): BackendFinding {
	const check = "service.daemon";
	let lock: LockRecord | undefined;
	try {
		lock = readJson<LockRecord>(paths.lock);
	} catch {
		lock = undefined;
	}
	const running = config.backend === "systemd" ? run("systemctl", ["--user", "is-active", DAEMON_UNIT], home).stdout.trim() === "active" : sameProcess(lock?.pid, OUTER_ARGV, probe);
	if (!running) return { check, severity: "warn", what: `cp-daemon is not running (${config.backend} backend)`, fix: `start it: ${startCommand(config)}; then cp-daemon status` };
	let state: DaemonState | undefined;
	let runtime: RuntimeRecord | undefined;
	try {
		state = readJson<DaemonState>(paths.state);
		runtime = readJson<RuntimeRecord>(paths.runtime);
	} catch (error) {
		return { check, severity: "warn", what: `cp-daemon runs, but its records are unreadable: ${(error as Error).message}`, fix: "cp-daemon log, then cp-daemon reload" };
	}
	const inner = state?.inner;
	if (inner && ["crash_looping", "failed", "not_ready"].includes(inner.state)) return { check, severity: "warn", what: `cp-daemon's runtime is ${inner.state}${inner.detail ? `: ${inner.detail}` : ""}`, fix: "cp-daemon log, then cp-daemon reload" };
	const parent = runtime?.units.parent;
	if (parent?.state === "failed") {
		return parent.result === "exit-code"
			? { check, severity: "warn", what: "cp-daemon: the parent supervisor stopped: no parent model (exit 78)", fix: "pin a model: cp-install --parent-model <provider/model> --force" }
			: { check, severity: "warn", what: `cp-daemon: the parent supervisor is failed (${parent.result ?? "failed"})${parent.result === "start-limit-hit" ? " — a crash loop" : ""}`, fix: "cp-daemon log, then cp-daemon reload" };
	}
	const viewer = runtime?.units.viewer;
	if (viewer && !["running", "starting", "held"].includes(viewer.state)) return { check, severity: "warn", what: `cp-daemon: the viewer is ${viewer.state}`, fix: "cp-daemon log (it binds CP_VIEWER_HOST, else `tailscale ip -4`); pin one with cp-install --viewer-host <ip> --force" };
	let onDisk: string | undefined;
	try {
		onDisk = outerHash(join(config.app, "src/service"));
	} catch {
		onDisk = undefined; // the checkout cannot be hashed: nothing to compare
	}
	if (state && onDisk && state.outer_hash !== onDisk) return { check, severity: "warn", what: `cp-daemon's outer (${state.outer_hash.slice(0, 12)}) predates the code on disk (${onDisk.slice(0, 12)}); a reload never replaces it`, fix: "cp-daemon restart at a quiet point (the parent host and workers keep running)" };
	return { check, severity: "ok", what: `cp-daemon running${state ? ` pid ${state.pid}` : ""} (${config.backend}): parent ${parent?.state ?? "unknown"}, viewer ${viewer?.state ?? "unknown"}` };
}

/**
 * True when a missing viewer is a fault: cp-daemon runs one (`data/daemon.json`) and no update holds it, or a
 * legacy cp-view.service is enabled.
 */
export function viewerExpected(run: FindRun, home: string, unitDir: string): boolean {
	const paths = daemonPaths(home);
	if (existsSync(paths.config)) return parse<RuntimeRecord>(fileText(paths.runtime))?.units?.viewer?.state !== "held";
	if (!(fileText(join(unitDir, VIEW)) ?? "").includes(GENERATED)) return false;
	return run("systemctl", ["--user", "is-enabled", VIEW], home).stdout.trim() === "enabled";
}
